// node tools/build_cert_fonts.js  -- regenerate engine/vendor/fonts/cert_fonts_data.js from the vendored woff2 files.
// The certificate embeds these faces as data URIs: an SVG rasterized through <img> cannot reach page fonts, and
// fetch() of a local woff2 fails from file://, so the bytes ship as a classic script that is loaded on demand.
const fs = require('fs');
const path = require('path');

const dir = path.resolve(__dirname, '..', 'engine', 'vendor', 'fonts');
const LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
const LATIN_EXT = 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF';

/* family, style, weight, file (relative to vendor/fonts), unicode-range; the Google Fonts css2 subsets of 2026-11-23 */
const FACES = [
  ['UnifrakturMaguntia', 'normal', 400, 'UnifrakturMaguntia/UnifrakturMaguntia-Regular.latin.woff2', LATIN],
  ['Pinyon Script', 'normal', 400, 'PinyonScript/PinyonScript-Regular.latin.woff2', LATIN],
  ['Pinyon Script', 'normal', 400, 'PinyonScript/PinyonScript-Regular.latin-ext.woff2', LATIN_EXT],
  ['Great Vibes', 'normal', 400, 'GreatVibes/GreatVibes-Regular.latin.woff2', LATIN],
  ['Great Vibes', 'normal', 400, 'GreatVibes/GreatVibes-Regular.latin-ext.woff2', LATIN_EXT],
  ['Cinzel Decorative', 'normal', 400, 'CinzelDecorative/CinzelDecorative-Regular.latin.woff2', LATIN],
  ['Cinzel Decorative', 'normal', 700, 'CinzelDecorative/CinzelDecorative-Bold.latin.woff2', LATIN],
  ['IM Fell English', 'normal', 400, 'IMFellEnglish/IMFellEnglish-Regular.latin.woff2', LATIN],
  ['IM Fell English', 'italic', 400, 'IMFellEnglish/IMFellEnglish-Italic.latin.woff2', LATIN],
];

const out = FACES.map(([family, style, weight, file, range]) => {
  const b64 = fs.readFileSync(path.join(dir, file)).toString('base64');
  return '  ' + JSON.stringify({ family, style, weight, range, file, data: b64 });
});
const js = '/* Generated by tools/build_cert_fonts.js from the woff2 files in this folder (SIL Open Font License 1.1, see each OFL.txt). Do not edit. */\n'
  + 'window.LMS_CERT_FONTS = [\n' + out.join(',\n') + '\n];\n';
fs.writeFileSync(path.join(dir, 'cert_fonts_data.js'), js);
console.log('wrote cert_fonts_data.js, ' + js.length + ' bytes, ' + FACES.length + ' faces');
